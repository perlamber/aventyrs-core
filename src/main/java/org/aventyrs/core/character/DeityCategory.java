package org.aventyrs.core.character;

/**
 * The tier a {@link Deity} belongs to, per the setting's cosmology — from no patron at all
 * up through Primordial gods. Purely descriptive grouping; nothing in this core currently
 * varies behavior by category.
 */
public enum DeityCategory {
    NENHUMA,
    DEUS_PRIMORDIAL,
    DEUS_ELEMENTAL,
    DEUS_GUIA,
    SENHOR_UMBRAL
}
